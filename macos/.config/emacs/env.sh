#!/bin/sh
# Write ~/.env.el, which early-init.el loads: PATH, exec-path and the variables
# below as an interactive login shell sets them, so Emacs never starts a shell
# at startup.  Re-run after changing the shell's environment; setup.sh does.
set -e
ENV_VARS="PATH MANPATH SSH_AUTH_SOCK SSH_AGENT_PID GPG_AGENT_INFO LANG LC_CTYPE
NIX_SSL_CERT_FILE NIX_PATH ASPELL_CONF DICPATH CFLAGS LDFLAGS PKG_CONFIG_PATH
XDG_DATA_HOME XDG_CONFIG_HOME XDG_CACHE_HOME"
ENV_EL='
(with-temp-file "~/.env.el"
  (insert ";;; -*- lexical-binding: t; -*- generated by ~/.config/emacs/env.sh\n")
  (dolist (var (split-string (getenv "ENV_VARS")))
    (when (getenv var)
      (prin1 `(setenv ,var ,(getenv var)) (current-buffer))
      (insert "\n")))
  (insert "(setq exec-path (append (parse-colon-path (getenv \"PATH\")) (list exec-directory)))\n"))'
# A clean environment, as Emacs.app gets from launchd: only what the shell's own
# config sets is written, and Emacs keeps its own value of the rest.  The
# prompt setup complains without a terminal; only emacs's status counts.
env -i HOME="$HOME" USER="$USER" LOGNAME="$LOGNAME" SHELL="${SHELL:-/bin/zsh}" \
  ${LANG:+LANG="$LANG"} ENV_VARS="$ENV_VARS" ENV_EL="$ENV_EL" \
  "${SHELL:-/bin/zsh}" -l -i -c 'emacs -Q --batch --eval "$ENV_EL"' 2>/dev/null </dev/null
echo "wrote ~/.env.el"
